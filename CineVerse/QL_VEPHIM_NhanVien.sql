/* ============================================================================
   NHÂN VIÊN: CHECK-IN VÉ + BÁN VÉ TẠI QUẦY
   Chạy SAU khi đã chạy QL_VEPHIM.sql. Có thể chạy lại nhiều lần.
   1) Thêm trạng thái vé N'Đã check-in'
   2) Tạo dữ liệu demo cho ngày hôm nay (suất LC101 + vài vé đã thanh toán)
   ============================================================================ */
USE QL_VEPHIM;
GO

DECLARE @tenRangBuoc NVARCHAR(200);
SELECT @tenRangBuoc = cc.name
FROM sys.check_constraints cc
WHERE cc.parent_object_id = OBJECT_ID('VE') AND cc.definition LIKE N'%Đã đặt%';

IF @tenRangBuoc IS NOT NULL
    EXEC('ALTER TABLE VE DROP CONSTRAINT ' + @tenRangBuoc);
GO

ALTER TABLE VE ADD CONSTRAINT CK_VE_TRANGTHAI
    CHECK (TRANGTHAI IN (N'Đã hủy', N'Đã đặt', N'Đã thanh toán', N'Đã check-in'));
GO

/* ---- Dữ liệu demo: suất chiếu hôm nay tại rạp A01 (nhân viên TK005) ---- */
DECLARE @khungGio NCHAR(5);
SELECT TOP 1 @khungGio = MA_KHUNGGIO
FROM KHUNGGIO
WHERE CAST(GETDATE() AS TIME) BETWEEN DATEADD(MINUTE, -60, GIOBATDAU) AND GIOKETTHUC
ORDER BY GIOBATDAU;
IF @khungGio IS NULL SET @khungGio = 'KG06';

IF NOT EXISTS (SELECT 1 FROM LICHCHIEU WHERE MA_LICHCHIEU = 'LC101')
    INSERT INTO LICHCHIEU VALUES ('LC101', 'P0001', 'PA01', @khungGio, CAST(GETDATE() AS DATE), 0);
ELSE
    UPDATE LICHCHIEU SET NGAYCHIEU = CAST(GETDATE() AS DATE), MA_KHUNGGIO = @khungGio WHERE MA_LICHCHIEU = 'LC101';

IF NOT EXISTS (SELECT 1 FROM DONHANG WHERE MA_DONHANG = 'DH003')
    INSERT INTO DONHANG (MA_DONHANG, MA_KHACHHANG, MA_NHANVIEN, MA_LICHCHIEU, MA_KM, NGAYDAT, TIENVE, TIENMONAN, TIENGIAM, TONGTIEN, TRANGTHAI)
    VALUES ('DH003', 'TK002', NULL, 'LC101', NULL, GETDATE(), 150000, 0, 0, 150000, N'DaThanhToan');

IF NOT EXISTS (SELECT 1 FROM DONHANG WHERE MA_DONHANG = 'DH004')
    INSERT INTO DONHANG (MA_DONHANG, MA_KHACHHANG, MA_NHANVIEN, MA_LICHCHIEU, MA_KM, NGAYDAT, TIENVE, TIENMONAN, TIENGIAM, TONGTIEN, TRANGTHAI)
    VALUES ('DH004', 'TK003', NULL, 'LC101', NULL, GETDATE(), 75000, 0, 0, 75000, N'DaThanhToan');

IF NOT EXISTS (SELECT 1 FROM VE WHERE MA_VE = 'VE004')
    INSERT INTO VE (MA_VE, MA_DONHANG, MA_LICHCHIEU, MA_GHE, DONGIA, TRANGTHAI) VALUES ('VE004', 'DH003', 'LC101', 'G0001', 75000, N'Đã thanh toán');
IF NOT EXISTS (SELECT 1 FROM VE WHERE MA_VE = 'VE005')
    INSERT INTO VE (MA_VE, MA_DONHANG, MA_LICHCHIEU, MA_GHE, DONGIA, TRANGTHAI) VALUES ('VE005', 'DH003', 'LC101', 'G0002', 75000, N'Đã thanh toán');
IF NOT EXISTS (SELECT 1 FROM VE WHERE MA_VE = 'VE006')
    INSERT INTO VE (MA_VE, MA_DONHANG, MA_LICHCHIEU, MA_GHE, DONGIA, TRANGTHAI) VALUES ('VE006', 'DH004', 'LC101', 'G0003', 75000, N'Đã thanh toán');

UPDATE VE SET TRANGTHAI = N'Đã thanh toán' WHERE MA_VE IN ('VE004', 'VE005', 'VE006');
GO
